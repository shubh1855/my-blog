/** Pure category URL helpers so route behavior can be checked without loading site config. */

export interface CategoryPathNode {
  name: string;
  children?: CategoryPathNode[];
}

/** Resolve one category name to its configured URL slug, failing clearly when absent. */
export function getCategorySlug(categoryName: string, mapping: Record<string, string>): string {
  const slug = mapping[categoryName];
  if (typeof slug !== 'string' || !slug.trim()) {
    throw new Error(
      `[category] Missing URL slug mapping for category "${categoryName}". Add a non-blank entry to categoryMap in config/site.yaml.`,
    );
  }

  return slug.trim().split('/').map(encodeURIComponent).join('/');
}

/** Build unique category route paths from the actual hierarchy. */
export function getCategoryLinks(
  categories: CategoryPathNode[] | undefined,
  parentLink: string | undefined,
  mapping: Record<string, string>,
): string[] {
  if (!categories?.length) return [];

  const links: string[] = [];
  const seenLinks = new Map<string, string>();
  const visit = (items: CategoryPathNode[], parent: string) => {
    for (const category of items) {
      const slug = getCategorySlug(category.name, mapping);
      const fullLink = parent ? `${parent}/${slug}` : slug;
      if (seenLinks.has(fullLink)) {
        const previous = seenLinks.get(fullLink);
        throw new Error(
          `[category] Duplicate category URL "/categories/${fullLink}" is generated by "${previous}" and "${category.name}". Give each category a unique path in categoryMap or category hierarchy.`,
        );
      }

      seenLinks.set(fullLink, category.name);
      links.push(fullLink);
      if (category.children?.length) visit(category.children, fullLink);
    }
  };

  visit(categories, parentLink ?? '');
  return links;
}
